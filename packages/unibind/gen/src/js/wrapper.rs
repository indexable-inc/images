//! Render `index.js`: the wrapper around the compiled artifact.
//!
//! The compiled glue only guarantees the low-level channel: camelCased
//! exports and `__unibind__:` failure messages. This wrapper is the user
//! surface, and it is the same surface for both flavors: it decodes reasons
//! into the generated `Error` subclasses, turns stream handles into
//! `AsyncIterable`s (early exit closes the producer), and wraps object handles
//! into classes with the resource close surface (`await using` works).
//!
//! What differs is how a module reaches the compiled exports and publishes
//! its own: node requires one addon object and assigns each export
//! individually so its cjs-module-lexer sees named exports, while the browser
//! imports each `wasm-bindgen` export under an alias and exports the set in
//! one ESM statement. [`Flavor`] owns every such difference; everything below
//! that does not mention it is shared verbatim.

use std::fmt::Write as _;

use unibind_core::ir;

use super::flavor::{Flavor, IMPORT_PREFIX};
use super::types::{self, doc_block, resource_close, type_name, value_name};

pub fn render(interface: &ir::Interface, flavor: &Flavor) -> String {
    let mut out = String::new();
    prelude(&mut out, interface, flavor);
    for error in &interface.errors {
        error_classes(&mut out, error);
    }
    decoder(&mut out, interface, flavor);
    if types::has_streams(interface) {
        out.push_str(STREAM_HELPER);
    }
    if !interface.objects.is_empty() {
        out.push_str(HANDLE_TOKEN);
    }
    if interface.objects.iter().any(|object| watched(flavor, object)) {
        out.push_str(LEAK_REGISTRY);
    }
    for object in &interface.objects {
        object_class(&mut out, interface, flavor, object);
    }
    for function in &interface.functions {
        function_wrapper(&mut out, interface, flavor, function);
    }
    exports(&mut out, interface, flavor);
    out
}

/// Whether this object's wrapper instances are watched for a missing close.
/// The same condition the close surface itself renders under, so a wrapper
/// cannot be registered with nothing to unregister it.
fn watched(flavor: &Flavor, object: &ir::Object) -> bool {
    flavor.watches_for_leaks() && resource_close(object).is_some()
}

/// The header, module loading, and (for the browser) the initializer
/// re-export: everything above the first generated class.
fn prelude(out: &mut String, interface: &ir::Interface, flavor: &Flavor) {
    match flavor {
        Flavor::Node { addon } => node_prelude(out, addon),
        Flavor::Browser { module } => browser_prelude(out, interface, module),
    }
}

fn node_prelude(out: &mut String, addon: &str) {
    out.push_str("\"use strict\";\n\n");
    out.push_str(
        "// Generated by `unibind-gen ts` from the interface embedded in the\n\
         // native addon; do not edit. The packaging step places the compiled\n",
    );
    writeln!(
        out,
        "// addon at ./native/{addon}.node next to this file.\n"
    )
    .expect("write to string");
    writeln!(out, "const native = require(\"./native/{addon}.node\");\n").expect("write to string");
    out.push_str(NORMALIZE_HELPER);
}

/// The ESM head: one aliased import of everything the wrappers below call,
/// then the module's own initializer re-exported.
///
/// No `"use strict"`: an ES module is strict already. The aliases are what
/// let the wrapper class keep the export's own name ([`IMPORT_PREFIX`]).
fn browser_prelude(out: &mut String, interface: &ir::Interface, module: &str) {
    out.push_str(
        "// Generated by `unibind-gen wasm` from the interface embedded in the\n\
         // wasm module; do not edit. Every wrapper below calls the\n\
         // `wasm-bindgen` module imported here.\n\n",
    );
    let specifier = crate::literal::double_quoted(module);
    let imported = imported_bindings(interface);
    if imported.is_empty() {
        writeln!(out, "import __wasm_init from {specifier};\n").expect("write to string");
    } else {
        out.push_str("import __wasm_init, {\n");
        for name in imported {
            writeln!(out, "  {name} as {IMPORT_PREFIX}{name},").expect("write to string");
        }
        writeln!(out, "}} from {specifier};\n").expect("write to string");
    }
    out.push_str(
        "// The module's own initializer, under both spellings a caller reaches\n\
         // for. It must be awaited once before anything below is called; the\n\
         // wasm module's own declarations are what type it.\n\
         export { __wasm_init as default, __wasm_init as init };\n\n",
    );
}

/// What the browser wrapper imports from the `wasm-bindgen` module: the
/// classes it constructs or calls a static on, then every free function.
///
/// A class the wrapper never names is left out. An object reached only as a
/// return value is constructed from the handle that call produced, so
/// importing its `wasm-bindgen` class would bind a name nothing reads.
fn imported_bindings(interface: &ir::Interface) -> Vec<String> {
    let classes = interface
        .objects
        .iter()
        .filter(|object| object.constructor.is_some() || !object.associated.is_empty())
        .map(|object| type_name(&object.names, &object.name).to_owned());
    let functions = interface
        .functions
        .iter()
        .map(|function| value_name(&function.name, &function.names));
    classes.chain(functions).collect()
}

// `undefined` and `null` both mean "unset", exactly as the declarations
// promise (`field?: T | null`). napi reads an Option-typed object field
// with `Object::get`, which reports absence only for `undefined` and hands
// a literal `null` to the field type's own conversion, which refuses it
// ("Failed to get property names of given object" for a map field, seen
// live). Normalizing here, at the one place every argument passes, keeps
// the published contract true without touching napi. Only plain object
// literals recurse: class instances (Buffer, AbortSignal, wrapper handles)
// cross untouched.
//
// The wasm boundary needs none of this, which is why the helper is the node
// prelude's and not shared: `serde_wasm_bindgen` reads `null` and
// `undefined` alike as `None` (`is_nullish` is `loose_eq(null)`), and
// `wasm-bindgen`'s own glue tests `x === undefined || x === null` for a
// native `Option` argument.
const NORMALIZE_HELPER: &str = "\
// `undefined` and `null` both mean \"unset\", as the declarations promise.
// The native layer reads absence only from `undefined`, so `null` is
// normalized away here for every argument at once.
function normalizeArg(value) {
  if (value === null) return undefined;
  if (Array.isArray(value)) return value.map(normalizeArg);
  if (
    typeof value === \"object\" &&
    Object.getPrototypeOf(value) === Object.prototype
  ) {
    const out = {};
    for (const [key, entry] of Object.entries(value)) {
      const normalized = normalizeArg(entry);
      if (normalized !== undefined) out[key] = normalized;
    }
    return out;
  }
  return value;
}

";

/// Watch every open resource wrapper for a missing close.
///
/// The Rust glue cannot: a wasm handle is freed when the engine frees it, and
/// no engine promises that ever happens, so a `Drop` that warned would fire
/// on some exits and not others (`unibind-backend-wasm`'s object module
/// leaves the job here for exactly that reason). A `FinalizationRegistry`
/// says it once, when a wrapper is collected while still open. A runtime
/// without one gets no warning, which is the only honest alternative to a
/// wrong one.
const LEAK_REGISTRY: &str = r#"// Warn once about a resource nobody closed: the wrapper is collected while
// still open. Guarded, because a runtime without a FinalizationRegistry can
// only be silent about it.
const leakRegistry =
  typeof FinalizationRegistry === "function"
    ? new FinalizationRegistry((name) => {
        console.warn(`unclosed ${name}: call close() or use \`await using\``);
      })
    : null;

// The wrapper is both the watched object and the unregister token, so
// closing it is what makes it silent. The held value is the class name:
// holding the wrapper would keep it alive and the warning could never fire.
function watchForLeak(wrapper, name) {
  if (leakRegistry !== null) {
    leakRegistry.register(wrapper, name, wrapper);
  }
}

function leakWatchClosed(wrapper) {
  if (leakRegistry !== null) {
    leakRegistry.unregister(wrapper);
  }
}

"#;

/// The base class carries `code` (the variant subclass name); each variant
/// subclass pins both `name` and `code`.
fn error_classes(out: &mut String, error: &ir::ErrorType) {
    let base = type_name(&error.names, &error.name);
    doc_block(out, "", &error.docs);
    writeln!(out, "class {base} extends Error {{").expect("write to string");
    out.push_str("  constructor(message, code) {\n    super(message);\n");
    writeln!(out, "    this.name = \"{base}\";").expect("write to string");
    out.push_str("    this.code = code;\n  }\n}\n");
    for variant in &error.variants {
        let name = type_name(&variant.names, &variant.name);
        doc_block(out, "", &variant.docs);
        writeln!(out, "class {name} extends {base} {{").expect("write to string");
        out.push_str("  constructor(message) {\n");
        writeln!(out, "    super(message, \"{name}\");").expect("write to string");
        writeln!(out, "    this.name = \"{name}\";").expect("write to string");
        out.push_str("  }\n}\n");
    }
    out.push('\n');
}

const ABORT_HELPER: &str = "\
function makeAbortError() {
  if (typeof DOMException === \"function\") {
    return new DOMException(\"This operation was aborted\", \"AbortError\");
  }
  const error = new Error(\"This operation was aborted\");
  error.name = \"AbortError\";
  return error;
}

";

const DECODE_HEAD: &str = "\
// Rethrow native failures as the generated classes; anything without the
// `__unibind__:` reason prefix passes through untouched.
function decodeError(error) {
  const reason =
    error instanceof Error && typeof error.message === \"string\" ? error.message : null;
  if (reason === null || !reason.startsWith(\"__unibind__:\")) {
    return error;
  }
  const rest = reason.slice(\"__unibind__:\".length);
  if (rest === \"aborted\") {
    return makeAbortError();
  }
";

const DECODE_TAIL: &str = "\
  if (rest.startsWith(\"err:\")) {
    const body = rest.slice(\"err:\".length);
    const nameEnd = body.indexOf(\":\");
    const variantEnd = body.indexOf(\":\", nameEnd + 1);
    if (nameEnd !== -1 && variantEnd !== -1) {
      const decode = (errorVariants[body.slice(0, nameEnd)] ?? {})[
        body.slice(nameEnd + 1, variantEnd)
      ];
      if (decode !== undefined) {
        return decode(body.slice(variantEnd + 1));
      }
    }
  }
  return error;
}

";

/// The decoder table (keyed by the Rust names spelled inside reasons), the
/// abort helper, and `decodeError` itself.
///
/// Both glues raise the same messages -- one wire vocabulary, whichever
/// artifact loaded -- so the decoder is shared down to the byte. Only the
/// convention the abort error follows is named per host.
fn decoder(out: &mut String, interface: &ir::Interface, flavor: &Flavor) {
    out.push_str("// Rust `<enum>` and `<variant>` names as spelled inside rejection reasons.\n");
    out.push_str("const errorVariants = {\n");
    for error in &interface.errors {
        writeln!(out, "  {}: {{", error.name).expect("write to string");
        for variant in &error.variants {
            writeln!(
                out,
                "    {}: (message) => new {}(message),",
                variant.name,
                type_name(&variant.names, &variant.name)
            )
            .expect("write to string");
        }
        out.push_str("  },\n");
    }
    out.push_str("};\n\n");
    writeln!(
        out,
        "// {} convention for cancelled operations: an error named AbortError.",
        flavor.abort_convention()
    )
    .expect("write to string");
    out.push_str(ABORT_HELPER);
    out.push_str(DECODE_HEAD);
    out.push_str(DECODE_TAIL);
}

const STREAM_HELPER: &str = "\
// Wrap the native pull handle into an AsyncIterable; leaving iteration
// early (break, return, throw) closes the stream, so the Rust producer
// sees its stream dropped and stops.
function wrapStream(handle) {
  const stream = {
    async next() {
      try {
        return await handle.next();
      } catch (error) {
        throw decodeError(error);
      }
    },
    close() {
      handle.close();
    },
    async *[Symbol.asyncIterator]() {
      try {
        for (;;) {
          const item = await stream.next();
          if (item === null) {
            return;
          }
          yield item;
        }
      } finally {
        stream.close();
      }
    },
  };
  return stream;
}

";

const HANDLE_TOKEN: &str = "\
// Internal marker: wrapper classes constructed around an existing native
// handle (function returns) instead of through the native constructor.
const nativeHandle = Symbol(\"unibind.nativeHandle\");

";

/// The wrapper class over one compiled object handle: the constructor (when
/// the object declares one), delegating methods with error decoding, and the
/// resource close surface with `await using` disposal.
fn object_class(out: &mut String, interface: &ir::Interface, flavor: &Flavor, object: &ir::Object) {
    let class = type_name(&object.names, &object.name);
    // Every path that binds a handle registers, including the one a returning
    // call takes: a wrapper built around an existing handle owns the resource
    // just as much as one that constructed it.
    let watch = watched(flavor, object).then(|| format!("watchForLeak(this, \"{class}\");"));
    doc_block(out, "", &object.docs);
    writeln!(out, "class {class} {{").expect("write to string");
    out.push_str("  #handle;\n\n");
    if let Some(ctor) = &object.constructor {
        doc_block(out, "  ", &ctor.docs);
        out.push_str("  constructor(...args) {\n");
        out.push_str("    if (args[0] === nativeHandle) {\n      this.#handle = args[1];\n");
        if let Some(watch) = &watch {
            writeln!(out, "      {watch}").expect("write to string");
        }
        out.push_str("      return;\n    }\n");
        out.push_str("    try {\n");
        writeln!(
            out,
            "      this.#handle = new {}({});",
            flavor.compiled(class),
            flavor.forwarded_args()
        )
        .expect("write to string");
        out.push_str("    } catch (error) {\n      throw decodeError(error);\n    }\n");
    } else {
        out.push_str("  /** Instances come from the exported functions returning this type. */\n");
        out.push_str("  constructor(...args) {\n");
        out.push_str("    if (args[0] !== nativeHandle) {\n");
        writeln!(
            out,
            "      throw new TypeError(\"{class} instances come from the exported functions that return them\");"
        )
        .expect("write to string");
        out.push_str("    }\n    this.#handle = args[1];\n");
    }
    if let Some(watch) = &watch {
        writeln!(out, "    {watch}").expect("write to string");
    }
    out.push_str("  }\n");
    for factory in &object.associated {
        factory_delegation(
            out,
            interface,
            flavor,
            factory,
            class,
            &value_name(&factory.name, &factory.names),
        );
    }
    let close = resource_close(object);
    for method in &object.methods {
        if close.is_some_and(|close| std::ptr::eq(close, method)) {
            continue;
        }
        method_delegation(
            out,
            interface,
            flavor,
            method,
            &value_name(&method.name, &method.names),
            None,
        );
    }
    if let Some(close) = close {
        // The generated close is idempotent; delegate it like any method, then
        // wire disposal through it. Unregistering first, not on success: the
        // caller did close, whatever the close itself reports.
        let closed = watch.is_some().then_some("leakWatchClosed(this);");
        method_delegation(out, interface, flavor, close, "close", closed);
        out.push_str("\n  /** `await using` support: closes the resource. */\n");
        out.push_str("  async [Symbol.asyncDispose]() {\n    await this.close();\n  }\n");
    }
    out.push_str("}\n\n");
}

/// One delegating static factory. Unlike a method it calls through the
/// compiled class rather than an instance handle, because the instance is
/// what it returns; the returned handle is wrapped into this wrapper class
/// the same way any object-returning call's is.
fn factory_delegation(
    out: &mut String,
    interface: &ir::Interface,
    flavor: &Flavor,
    factory: &ir::Function,
    class: &str,
    name: &str,
) {
    out.push('\n');
    doc_block(out, "  ", &factory.docs);
    let is_async = matches!(factory.asyncness, ir::Asyncness::Async);
    let call = format!(
        "{}.{name}({})",
        flavor.compiled(class),
        flavor.forwarded_args()
    );
    let call = if is_async {
        format!("await {call}")
    } else {
        call
    };
    let value = returned_value(interface, factory, call);
    if is_async {
        writeln!(out, "  static async {name}(...args) {{\n    try {{").expect("write to string");
    } else {
        writeln!(out, "  static {name}(...args) {{\n    try {{").expect("write to string");
    }
    writeln!(out, "      return {value};").expect("write to string");
    out.push_str("    } catch (error) {\n      throw decodeError(error);\n    }\n  }\n");
}

/// One delegating method: forward the positional arguments (async methods
/// take the optional trailing `AbortSignal` natively), decode failures, and
/// wrap stream and object returns exactly as a free function's do -- a method
/// handing back a raw handle would skip the wrapper class (and its error
/// decoding and disposal) the `.d.ts` promises.
///
/// `before` is a statement running ahead of the forward, which is where the
/// close of a watched resource stops being watched.
fn method_delegation(
    out: &mut String,
    interface: &ir::Interface,
    flavor: &Flavor,
    method: &ir::Function,
    name: &str,
    before: Option<&str>,
) {
    out.push('\n');
    doc_block(out, "  ", &method.docs);
    let is_async = matches!(method.asyncness, ir::Asyncness::Async);
    let call = format!("this.#handle.{name}({})", flavor.forwarded_args());
    let call = if is_async {
        format!("await {call}")
    } else {
        call
    };
    let value = returned_value(interface, method, call);
    if is_async {
        writeln!(out, "  async {name}(...args) {{").expect("write to string");
    } else {
        writeln!(out, "  {name}(...args) {{").expect("write to string");
    }
    if let Some(before) = before {
        writeln!(out, "    {before}").expect("write to string");
    }
    out.push_str("    try {\n");
    writeln!(out, "      return {value};").expect("write to string");
    out.push_str("    } catch (error) {\n      throw decodeError(error);\n    }\n  }\n");
}

/// What a wrapper hands back: stream handles become `AsyncIterable`s and
/// object handles their wrapper class; every other value crosses as the glue
/// produced it.
fn returned_value(interface: &ir::Interface, function: &ir::Function, call: String) -> String {
    match &function.ret {
        Some(ir::Type::Stream(_)) => format!("wrapStream({call})"),
        Some(ir::Type::Named(named)) => interface
            .objects
            .iter()
            .find(|object| object.name == *named)
            .map_or_else(
                || call.clone(),
                |object| {
                    format!(
                        "new {}(nativeHandle, {call})",
                        type_name(&object.names, &object.name)
                    )
                },
            ),
        _ => call,
    }
}

/// One exported function: forward the positional arguments (async exports
/// take the optional trailing `AbortSignal` natively), decode failures, and
/// wrap stream and object returns.
fn function_wrapper(
    out: &mut String,
    interface: &ir::Interface,
    flavor: &Flavor,
    function: &ir::Function,
) {
    let name = value_name(&function.name, &function.names);
    doc_block(out, "", &function.docs);
    let is_async = matches!(function.asyncness, ir::Asyncness::Async);
    let call = format!("{}({})", flavor.compiled(&name), flavor.forwarded_args());
    let call = if is_async {
        format!("await {call}")
    } else {
        call
    };
    let value = returned_value(interface, function, call);
    if is_async {
        writeln!(out, "async function {name}(...args) {{").expect("write to string");
    } else {
        writeln!(out, "function {name}(...args) {{").expect("write to string");
    }
    out.push_str("  try {\n");
    writeln!(out, "    return {value};").expect("write to string");
    out.push_str("  } catch (error) {\n    throw decodeError(error);\n  }\n}\n\n");
}

/// Everything the wrapper publishes, in one order both tails walk: the
/// functions, each error class with its variants, then the object classes.
fn exported_names(interface: &ir::Interface) -> Vec<String> {
    let mut names = Vec::new();
    for function in &interface.functions {
        names.push(value_name(&function.name, &function.names));
    }
    for error in &interface.errors {
        names.push(type_name(&error.names, &error.name).to_owned());
        for variant in &error.variants {
            names.push(type_name(&variant.names, &variant.name).to_owned());
        }
    }
    for object in &interface.objects {
        names.push(type_name(&object.names, &object.name).to_owned());
    }
    names
}

fn exports(out: &mut String, interface: &ir::Interface, flavor: &Flavor) {
    let names = exported_names(interface);
    match flavor {
        // One assignment per export so cjs-module-lexer detects the
        // named-export set and `import { ... }` works from ESM.
        Flavor::Node { .. } => {
            out.push_str("// Assign each binding as its own property so Node's cjs-module-lexer\n");
            out.push_str("// detects them as named exports.\n");
            for name in names {
                writeln!(out, "module.exports.{name} = {name};").expect("write to string");
            }
        }
        // An ES module says it once. The initializer is exported by the
        // prelude, next to the import it comes from.
        Flavor::Browser { .. } => {
            out.push_str("// The named exports the declarations promise.\n");
            out.push_str("export {\n");
            for name in names {
                writeln!(out, "  {name},").expect("write to string");
            }
            out.push_str("};\n");
        }
    }
}
