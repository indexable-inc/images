//! What the two JavaScript-family targets do differently.
//!
//! `index.d.ts`, `schemas.ts`, and `index.js` are one published surface with
//! two implementations under it: napi in node (`unibind-gen ts`) and
//! `wasm-bindgen` in a browser (`unibind-gen wasm`). The renderers next to
//! this module spell everything the two agree on exactly once, and every
//! place they differ asks here.
//!
//! Each difference is a fact about the binding library or the host, never a
//! preference. A record field's bytes are a `Buffer` because napi's mirror
//! struct declares one, while serde's twin field carries the array of numbers
//! serde makes of a `Vec<u8>` -- and a browser has no `Buffer` to declare at
//! all. The node wrapper `require`s a `CommonJS` addon where a wasm module
//! needs an ESM import and an awaited initializer.

/// Which JavaScript target is being rendered, carrying the one piece of
/// packaging its wrapper has to name.
pub enum Flavor {
    /// napi in node: `index.js` is `CommonJS` and requires
    /// `./native/<addon>.node` next to itself.
    Node {
        /// Basename of the compiled addon.
        addon: String,
    },
    /// `wasm-bindgen --target web` in a browser: `index.js` is an ES module
    /// importing the JavaScript half of the `wasm-bindgen` output, whose
    /// default export is the initializer.
    Browser {
        /// The module specifier the wrapper imports.
        module: String,
    },
}

/// Bytes inside a container: a `Vec` element or a map value. Both flavors
/// agree here, for the same reason -- the container crosses whole, so its
/// interior is whatever napi and serde make of a `Vec<u8>`.
pub const CONTAINED_BYTES: &str = "Array<number>";

/// The Zod schema checking [`CONTAINED_BYTES`].
pub const CONTAINED_BYTES_SCHEMA: &str = "z.array(z.number().int())";

/// The alias prefix the browser wrapper imports each compiled export under.
///
/// The wrapper defines a function and a class under the export's own name,
/// so the imported binding cannot keep it.
pub const IMPORT_PREFIX: &str = "__wasm_";

/// How one flavor spells a byte string outside a container, which is the
/// whole of what the two disagree about in the type mapping.
#[derive(Clone, Copy)]
pub struct Bytes {
    /// A whole argument, return value, or stream item.
    pub top: &'static str,
    /// A record field: the position that reads as "nested" and is not. napi
    /// declares its mirror field `Buffer` and accepts one in both
    /// directions; serde has no such carve-out, so a twin's field is the
    /// same array of numbers a container's interior is.
    pub field: &'static str,
    /// The Zod schema checking [`Self::field`].
    pub field_schema: &'static str,
    /// Whether the spellings above name node's `Buffer`, which is not a
    /// global: the declaration files import it when the interface has bytes
    /// at a position that spells one.
    pub imported: bool,
}

/// napi: a `Buffer` everywhere the glue converts the value itself.
const NODE_BYTES: Bytes = Bytes {
    top: "Buffer",
    field: "Buffer",
    field_schema: "z.instanceof(Buffer)",
    imported: true,
};

/// `wasm-bindgen`: a `Uint8Array` where the signature carries the bytes
/// itself (`unibind_backend_wasm::ty::js_value` builds the view), and
/// serde's array of numbers everywhere serde carries them.
const BROWSER_BYTES: Bytes = Bytes {
    top: "Uint8Array",
    field: CONTAINED_BYTES,
    field_schema: CONTAINED_BYTES_SCHEMA,
    imported: false,
};

impl Flavor {
    /// The `unibind-gen` subcommand these files came from, which is also the
    /// target name the emitter reports.
    pub const fn target(&self) -> &'static str {
        match self {
            Self::Node { .. } => "ts",
            Self::Browser { .. } => "wasm",
        }
    }

    /// What the banner calls the artifact the IR was read out of.
    const fn artifact(&self) -> &'static str {
        match self {
            Self::Node { .. } => "native addon",
            Self::Browser { .. } => "wasm module",
        }
    }

    /// The two comment lines `index.d.ts` and `schemas.ts` open with.
    pub fn banner(&self) -> String {
        format!(
            "// Generated by `unibind-gen {}` from the interface embedded in the\n\
             // {}; do not edit.\n",
            self.target(),
            self.artifact()
        )
    }

    /// The byte-string spellings this flavor uses.
    pub const fn bytes(&self) -> Bytes {
        match self {
            Self::Node { .. } => NODE_BYTES,
            Self::Browser { .. } => BROWSER_BYTES,
        }
    }

    /// How `index.js` names one compiled export: a free function, or the
    /// class its constructor and static factories hang off.
    ///
    /// The node wrapper reads every export off the one required addon
    /// object. The browser wrapper imports each one individually, renamed on
    /// the way in ([`IMPORT_PREFIX`]).
    pub fn compiled(&self, name: &str) -> String {
        match self {
            Self::Node { .. } => format!("native.{name}"),
            Self::Browser { .. } => format!("{IMPORT_PREFIX}{name}"),
        }
    }

    /// The argument list every wrapper forwards.
    ///
    /// node normalizes `null` to `undefined` on the way through (see
    /// `wrapper::NORMALIZE_HELPER` for what that fixes). The wasm boundary
    /// reads both as absent already -- `serde_wasm_bindgen`'s
    /// `deserialize_option` is `loose_eq(null)`, and `wasm-bindgen`'s own
    /// glue tests `x === undefined || x === null` -- so the browser wrapper
    /// forwards exactly what it was handed.
    pub const fn forwarded_args(&self) -> &'static str {
        match self {
            Self::Node { .. } => "...args.map(normalizeArg)",
            Self::Browser { .. } => "...args",
        }
    }

    /// Whose convention the abort error follows, the one host-specific word
    /// of the shared decoder.
    pub const fn abort_convention(&self) -> &'static str {
        match self {
            Self::Node { .. } => "Node's",
            Self::Browser { .. } => "The web platform's",
        }
    }

    /// Whether the wrapper watches for resources nobody closed.
    ///
    /// The node and Python glue warn from `Drop`. wasm has no Drop-at-GC
    /// story -- a handle is freed when JavaScript frees it, and no engine
    /// promises that ever happens -- so `unibind-backend-wasm` renders no
    /// warning and leaves the job here, where a `FinalizationRegistry` can
    /// say it without a false negative.
    pub const fn watches_for_leaks(&self) -> bool {
        matches!(self, Self::Browser { .. })
    }
}
